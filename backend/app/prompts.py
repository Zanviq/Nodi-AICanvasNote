def answer_user_message(question: str, nearby: str | None, title: str | None) -> str:
    parts: list[str] = []
    if title:
        parts.append(f"[쪽 제목]\n{title}")
    if nearby:
        parts.append(f"[주변 필기]\n{nearby}")
    parts.append(f"[질문]\n{question}")
    return "\n\n".join(parts)
